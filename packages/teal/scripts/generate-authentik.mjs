import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { colorTokens, sharedTokens } from '../token-source.mjs'
import { akVariables, authentikVersion, pfDarkVariables, pfLightVariables, pfVariables } from '../authentik-source.mjs'

const packageRoot = resolve(import.meta.dirname, '..')
const cssPath = resolve(packageRoot, 'src/authentik.css')

function declarations(values) {
  return Object.entries(values)
    .map(([name, value]) => `  ${name.startsWith('--') ? name : `--${name}`}: ${value};`)
    .join('\n')
}

function tealTokens(scheme) {
  return Object.fromEntries(
    Object.entries(colorTokens).map(([name, token]) => [name, `rgb(${token[scheme].join(' ')})`]),
  )
}

function pf5Variables(values) {
  return Object.fromEntries(
    Object.entries(values).map(([name, value]) => [name.replace('--pf-global--', '--pf-v5-global--'), value]),
  )
}

function pfBlock(themeVariables) {
  const merged = { ...pfVariables, ...themeVariables }
  return `  /* PatternFly 4 global variables */
${declarations(merged)}
  /* PatternFly 5 global variables */
${declarations(pf5Variables(merged))}`
}

function renderCss() {
  return `/* Generated by scripts/generate-authentik.mjs. Do not edit directly. */
/* Teal adapter for Authentik ${authentikVersion}: maps Teal tokens onto supported
/* Authentik and PatternFly 4/5 variables and exposed CSS parts. Do not target
/* private shadow-DOM structure. Verify reference screenshots before upgrading. */
:root {
  color-scheme: light;
${declarations(tealTokens('light'))}
${declarations(sharedTokens)}
  /* Authentik variables */
${declarations(akVariables)}
${pfBlock(pfLightVariables)}
}

:root[data-theme="dark"] {
  color-scheme: dark;
${declarations(tealTokens('dark'))}
  /* Authentik variables */
${declarations(akVariables)}
${pfBlock(pfDarkVariables)}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --pf-global--TransitionDuration: 0.01ms;
    --pf-v5-global--TransitionDuration: 0.01ms;
  }
}
`
}

const check = process.argv.includes('--check')
if (check) {
  let actual
  try {
    actual = await readFile(cssPath, 'utf8')
  } catch {
    throw new Error('Generated Authentik adapter is missing. Run npm run generate:authentik.')
  }
  if (actual !== renderCss()) {
    throw new Error('Generated Authentik adapter is stale. Run npm run generate:authentik.')
  }
} else {
  await writeFile(cssPath, renderCss())
  console.log('Generated Authentik adapter')
}
